"""Canonical pre-production baseline for the shared establishment counting ledger."""

ESTABLISHMENT_SCHEMA = (
    """create table establishment_observations (
        observation_id text not null,
        business_date text not null,
        camera_id integer not null,
        analysis_mode text not null check(analysis_mode in ('entrance_exit','open_space')),
        kind text not null check(kind in ('entry','exit','area_visit')),
        track_key text not null,
        revision_id text,
        model_name text,
        visitor_id text,
        identity_confidence text not null,
        reid_decision text not null,
        reid_score real,
        qualified integer not null check(qualified in (0,1)),
        first_at text not null,
        last_at text not null,
        ended_at text,
        arrival_observed integer not null check(arrival_observed in (0,1)),
        departure_observed integer not null check(departure_observed in (0,1)),
        coverage_json text not null,
        population_key text not null,
        population_context_json text not null,
        payload_json text not null,
        primary key(observation_id,business_date))""",
    "create index idx_establishment_observations_day on establishment_observations(business_date,qualified)",
    "create index idx_establishment_observations_visitor on establishment_observations(visitor_id)",
    "create index idx_establishment_observations_track on establishment_observations(track_key,business_date)",
    """create table establishment_daily_summaries (
        business_date text primary key,
        metrics_json text not null,
        policy_version integer not null,
        finalized integer not null default 0 check(finalized in (0,1)),
        updated_at text not null)""",
    """create table establishment_occupancy_intervals (
        interval_id integer primary key,
        start_at text not null,
        end_at text not null,
        occupancy integer check(occupancy >= 0),
        completeness text not null,
        sources_json text not null,
        end_sources_json text not null,
        unique(start_at))""",
    "create index idx_establishment_occupancy_time on establishment_occupancy_intervals(end_at)",
    """create table establishment_population_openings (
        population_key text primary key,
        opening_occupancy integer not null check(opening_occupancy >= 0),
        partial integer not null default 0 check(partial in (0,1)),
        anchored integer not null default 0 check(anchored in (0,1)),
        through_date text not null)""",
    """create table establishment_population_anchors (
        population_key text not null,
        business_date text not null,
        observed_at text not null,
        occupancy integer not null check(occupancy >= 0),
        source_camera_ids_json text not null,
        evidence_json text not null,
        primary key(population_key,business_date))""",
)
