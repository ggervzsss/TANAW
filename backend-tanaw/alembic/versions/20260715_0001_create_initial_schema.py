def _install_database_ddl() -> None:
    """Install sequences, guards, triggers, and rolling partitions."""

    statements = _DATABASE_DDL_PATH.read_text(encoding="utf-8").split(_DDL_DELIMITER)
    for statement in statements:
        normalized = statement.strip()
        if normalized:
            op.execute(sa.text(normalized))


